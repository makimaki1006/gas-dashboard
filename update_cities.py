def main():
    with open('GeoData.js', 'r', encoding='utf-8') as f:
        content = f.read()

    # CITY_COORDINATESの終わりを探す（"那覇市": の行の後）
    # パターン: "那覇市": [26.2124, 127.6809]\n};

    import re

    # 既存のエントリの後に追加する座標を生成
    additional_entries = []
    for city, coords in ADDITIONAL_CITIES.items():
        # 既に存在するかチェック
        if f'"{city}"' not in content:
            additional_entries.append(f'  "{city}": [{coords[0]}, {coords[1]}]')

    if not additional_entries:
        print("追加する座標はありません（全て既存）")
        return

    # 既存のCITY_COORDINATESの最後のエントリを探して、その後に追加
    # "那覇市": [26.2124, 127.6809] の後に追加

    old_ending = '"那覇市": [26.2124, 127.6809]\n};'
    new_entries_str = ',\n'.join(additional_entries)
    new_ending = f'"那覇市": [26.2124, 127.6809],\n{new_entries_str}\n}};'

    if old_ending in content:
        content = content.replace(old_ending, new_ending)
        print(f"{len(additional_entries)}件の座標を追加しました")
    else:
        print("パターンが見つかりません。手動で確認してください。")
        # 代替パターンを試す
        alt_pattern = r'"那覇市":\s*\[26\.2124,\s*127\.6809\]\s*\n\};'
        if re.search(alt_pattern, content):
            content = re.sub(alt_pattern, new_ending, content)
            print(f"代替パターンで{len(additional_entries)}件の座標を追加しました")
        else:
            print("代替パターンも見つかりません")
            return

    with open('GeoData.js', 'w', encoding='utf-8') as f:
        f.write(content)

    print("GeoData.js を更新しました")

if __name__ == '__main__':
    main()
