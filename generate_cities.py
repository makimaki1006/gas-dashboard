def main():
    # GeoData.jsを読み込み
    with open('GeoData.js', 'r', encoding='utf-8') as f:
        content = f.read()

    # CITY_COORDINATESを新しいデータで置き換え
    # 既存のCITY_COORDINATES定義を探す
    pattern = r'const CITY_COORDINATES = \{[^}]+\};'

    # 新しいCITY_COORDINATESを生成
    new_coords = "const CITY_COORDINATES = {\n"
    for city, coords in JAPAN_CITIES.items():
        new_coords += f'  "{city}": [{coords[0]}, {coords[1]}],\n'
    new_coords = new_coords.rstrip(',\n') + "\n};"

    # 置き換え
    if re.search(pattern, content, re.DOTALL):
        # 複数行にまたがるパターンを検索
        start = content.find('const CITY_COORDINATES = {')
        if start != -1:
            # 対応する閉じ括弧を探す
            brace_count = 0
            end = start
            for i, char in enumerate(content[start:], start):
                if char == '{':
                    brace_count += 1
                elif char == '}':
                    brace_count -= 1
                    if brace_count == 0:
                        end = i + 1
                        # セミコロンがあれば含める
                        if end < len(content) and content[end] == ';':
                            end += 1
                        break

            content = content[:start] + new_coords + content[end:]
            print(f"CITY_COORDINATES を {len(JAPAN_CITIES)} 件のデータで更新しました")
        else:
            print("CITY_COORDINATESが見つかりません")
            return
    else:
        print("パターンが見つかりません")
        return

    # ファイルに書き込み
    with open('GeoData.js', 'w', encoding='utf-8') as f:
        f.write(content)

    print(f"GeoData.js を更新しました（{len(JAPAN_CITIES)} 市区町村）")

if __name__ == '__main__':
    main()
